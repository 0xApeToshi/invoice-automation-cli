@app.command()
def setup(
    provider: str = typer.Option(
        "both",
        "--provider",
        "-p",
        help="Provider to set up: meta, google, or both",
    ),
    interactive: bool = typer.Option(
        True,
        "--interactive/--non-interactive",
        help="Use interactive setup wizard",
    ),
) -> None:
    """
    Interactive setup wizard for configuring API credentials.
    
    This command guides you through the process of setting up API credentials
    for Meta Ads and Google Ads, creating the necessary configuration files.
    
    Examples:
        invoice-automation setup --provider meta
        invoice-automation setup --interactive
    """
    if interactive:
        _run_interactive_setup(provider)
    else:
        _display_setup_instructions(provider)


def _run_interactive_setup(provider: str) -> None:
    """
    Run the interactive setup wizard.
    
    Args:
        provider: Provider to set up
    """
    console.print("[bold blue]Invoice Automation Setup Wizard[/bold blue]\n")
    
    env_path = Path(".env")
    
    if env_path.exists():
        overwrite = typer.confirm(
            f".env file already exists. Do you want to overwrite it?",
            default=False,
        )
        if not overwrite:
            console.print("[yellow]Setup cancelled.[/yellow]")
            return
    
    console.print("This wizard will help you configure your API credentials.\n")
    
    config_lines = [
        "# Invoice Automation Configuration",
        "# Generated by setup wizard",
        "",
        "# Application Configuration",
        "OUTPUT_DIR=./invoices",
        "LOG_LEVEL=INFO",
        "MAX_RETRIES=3",
        "RETRY_DELAY=1.0",
        "TIMEOUT_SECONDS=30",
        "DEBUG=false",
        "",
    ]
    
    if provider in ["meta", "both"]:
        console.print("[bold]Meta Ads Configuration[/bold]")
        console.print("You'll need a Meta Business Manager account with Finance role.")
        console.print("Visit https://business.facebook.com/ to get your credentials.\n")
        
        business_id = typer.prompt("Meta Business ID")
        access_token = typer.prompt("Meta Access Token", hide_input=True)
        api_version = typer.prompt("Meta API Version", default="v21.0")
        
        config_lines.extend([
            "# Meta Ads Configuration",
            f"META_BUSINESS_ID={business_id}",
            f"META_ACCESS_TOKEN={access_token}",
            f"META_API_VERSION={api_version}",
            "",
        ])
    
    if provider in ["google", "both"]:
        console.print("[bold]Google Ads Configuration[/bold]")
        console.print("You'll need Google Ads API credentials and OAuth2 setup.")
        console.print("Visit https://developers.google.com/google-ads/api/ for setup instructions.\n")
        
        customer_id = typer.prompt("Google Ads Customer ID")
        client_id = typer.prompt("OAuth2 Client ID")
        client_secret = typer.prompt("OAuth2 Client Secret", hide_input=True)
        refresh_token = typer.prompt("OAuth2 Refresh Token", hide_input=True)
        developer_token = typer.prompt("Google Ads Developer Token", hide_input=True)
        
        config_lines.extend([
            "# Google Ads Configuration",
            f"GOOGLE_CUSTOMER_ID={customer_id}",
            f"GOOGLE_CLIENT_ID={client_id}",
            f"GOOGLE_CLIENT_SECRET={client_secret}",
            f"GOOGLE_REFRESH_TOKEN={refresh_token}",
            f"GOOGLE_DEVELOPER_TOKEN={developer_token}",
            "",
        ])
    
    # Write configuration file
    try:
        with open(env_path, "w") as f:
            f.write("\n".join(config_lines))
        
        console.print(f"\n[green]Configuration saved to {env_path}[/green]")
        console.print("\nNext steps:")
        console.print("1. Run 'invoice-automation status' to test your configuration")
        console.print("2. Run 'invoice-automation fetch' to retrieve invoices")
        
    except Exception as e:
        console.print(f"[red]Failed to save configuration: {e}[/red]")
        raise typer.Exit(1)


