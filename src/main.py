"""
Main entry point for the invoice automation CLI application.

This module defines the main Typer application and registers all available
commands. It serves as the primary interface for users interacting with
the invoice automation system.
"""

import sys
from pathlib import Path
from typing import Any

import typer
from rich.console import Console
from rich.traceback import install

from .commands.fetch import fetch_command
from .commands.status import status_command

# Install rich traceback handler for better error display
install(show_locals=True)

console = Console()

# Create the main Typer application
app = typer.Typer(
    name="invoice-automation",
    help="Automate invoice retrieval from Google Ads and Meta Ads",
    add_completion=False,
    rich_markup_mode="rich",
    context_settings={"help_option_names": ["-h", "--help"]},
)

# Register commands
app.command("fetch", help="Fetch invoices from configured providers")(fetch_command)
app.command("status", help="Check provider configuration and API connections")(status_command)


def version_callback(value: bool) -> None:
    """
    Display version information and exit.
    
    Args:
        value: Whether version was requested
    """
    if value:
        console.print("invoice-automation version 0.1.0")
        raise typer.Exit()


